// backend/src/test/confluence-adf.test.ts
import { describe, it, expect } from 'vitest';
import {
  doc, h, p, text, generated, findGenerated, replaceGenerated, adfText, GENERATED, sectionContent, normalizeForCompare, table,
  type AdfDoc,
} from '../../../shared/confluence-adf';

function hubLike(): AdfDoc {
  return doc([
    h(2, 'Status'),
    generated('status', [p(text('old status'))]),
    h(2, 'Links'),
    p(text('hand-written link notes')),
    generated('checklist', [p(text('old checklist'))]),
  ]);
}

describe('generated sections', () => {
  it('replaces only the marked section', () => {
    const before = hubLike();
    const res = replaceGenerated(before, 'status', [p(text('new status'))]);
    expect(res.replaced).toBe(true);
    expect(adfText(res.doc.content[1])).toContain('new status');
    expect(adfText(res.doc.content[1])).not.toContain('old status');
    expect(res.doc.content[3]).toEqual(before.content[3]);
    expect(res.doc.content[4]).toEqual(before.content[4]);
  });

  it('does not mutate the input', () => {
    const before = hubLike();
    const snapshot = JSON.parse(JSON.stringify(before));
    replaceGenerated(before, 'checklist', [p(text('x'))]);
    expect(before).toEqual(snapshot);
  });

  it('finds the expand fallback form', () => {
    const d = doc([
      { type: 'expand', attrs: { title: GENERATED.status.title }, content: [p(text('old'))] },
    ]);
    expect(findGenerated(d, 'status')).toEqual([0]);
    const res = replaceGenerated(d, 'status', [p(text('new'))]);
    expect(res.replaced).toBe(true);
    expect(res.doc.content[0].type).toBe('expand');
    expect(adfText(res.doc)).toContain('new');
  });

  it('reports a missing marker without changing the doc', () => {
    const d = doc([p(text('no markers here'))]);
    const res = replaceGenerated(d, 'status', [p(text('new'))]);
    expect(res).toEqual({ doc: d, replaced: false, reason: 'missing' });
  });

  it('refuses to guess when a marker is duplicated', () => {
    const d = doc([generated('status', [p(text('a'))]), generated('status', [p(text('b'))])]);
    const res = replaceGenerated(d, 'status', [p(text('new'))]);
    expect(res).toMatchObject({ replaced: false, reason: 'duplicate' });
  });

  it('generated sections start with a do-not-edit note', () => {
    expect(adfText(generated('checklist', []))).toContain('Generated by the doc check');
  });
});

describe('settings section and change detection', () => {
  it('has a settings marker', () => {
    expect(GENERATED.settings.label).toBe('doc-check-settings');
  });

  it('reads a section back without the note', () => {
    const d = doc([generated('status', [p(text('hello'))])]);
    expect(sectionContent(d, 'status')).toEqual([p(text('hello'))]);
    expect(sectionContent(d, 'checklist')).toBeNull();
  });

  it('ignores ids Confluence adds', () => {
    const ours = [p(text('a'))];
    const theirs = [{ type: 'paragraph', attrs: { localId: 'x1' }, content: [{ type: 'text', text: 'a' }] }];
    expect(normalizeForCompare(theirs)).toEqual(normalizeForCompare(ours));
  });

  it('ignores key order', () => {
    expect(JSON.stringify(normalizeForCompare({ type: 'text', text: 'a' }))).toBe(JSON.stringify(normalizeForCompare({ text: 'a', type: 'text' })));
  });

  it('treats the table attrs Confluence fills in as defaults', () => {
    const ours = table(['A'], [[[text('x')]]]);
    const theirs = JSON.parse(JSON.stringify(ours));
    theirs.attrs = { layout: 'default', localId: 'z' };
    for (const row of theirs.content) for (const cell of row.content) cell.attrs = { colspan: 1, rowspan: 1 };
    expect(normalizeForCompare(theirs)).toEqual(normalizeForCompare(ours));
    const wide = JSON.parse(JSON.stringify(theirs));
    wide.content[0].content[0].attrs.colspan = 2;
    expect(normalizeForCompare(wide)).not.toEqual(normalizeForCompare(ours));
  });

  it('ignores the title slug Confluence drops from page links', () => {
    const link = (href: string) => ({ type: 'text', text: 'PRD', marks: [{ type: 'link', attrs: { href } }] });
    const base = 'https://minted.atlassian.net/wiki/spaces/PM/pages/123';
    expect(normalizeForCompare(link(base))).toEqual(normalizeForCompare(link(`${base}/Brief+PRD+Thing`)));
    expect(normalizeForCompare(link(base))).not.toEqual(normalizeForCompare(link(`${base}4`)));
  });
});
